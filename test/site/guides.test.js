'use strict';

// The guides are plain Markdown that GitHub also shows, so their title, description, layout and
// place in the guide list live beside them rather than in them. Nothing would notice a guide that
// was added without any of that: it would publish with the site's default title and no sidebar entry.

const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { test } = require('node:test');

const root = path.join(__dirname, '..', '..');
const DOCS = path.join(root, 'docs');
const yaml = require(path.join(root, 'app', 'node_modules', 'js-yaml'));

const config = yaml.load(fs.readFileSync(path.join(DOCS, '_config.yml'), 'utf8'));
const groups = yaml.load(fs.readFileSync(path.join(DOCS, '_data', 'guides.yml'), 'utf8'));

// changelog.md is generated with its own front matter; README.md is the hub the list links to.
const guides = fs
  .readdirSync(DOCS)
  .filter((name) => name.endsWith('.md'))
  .map((name) => name.slice(0, -3));

test('every guide is in the guide list exactly once', () => {
  const listed = groups.flatMap((group) => group.items.map((item) => item.file));
  assert.equal(new Set(listed).size, listed.length, 'a guide is listed twice');

  for (const guide of guides.filter((name) => name !== 'README')) {
    assert.ok(listed.includes(guide), `docs/${guide}.md is not in docs/_data/guides.yml, so no sidebar links to it`);
  }
  for (const file of listed) {
    assert.ok(guides.includes(file), `docs/_data/guides.yml lists ${file}, which is not a guide`);
  }
  for (const group of groups) {
    assert.ok(group.title && group.items.length, 'a group needs a title and guides');
    for (const item of group.items) assert.ok(item.label, `${item.file} has no label`);
  }
});

test('every guide has a title and a description of its own', () => {
  const byPath = new Map(config.defaults.map((entry) => [entry.scope.path, entry.values]));

  for (const guide of guides) {
    if (guide === 'changelog') {
      // Generated by tools/site/changelog.js with its own front matter.
      continue;
    }
    const values = byPath.get(`${guide}.md`);
    assert.ok(values, `docs/_config.yml has no defaults entry for ${guide}.md`);
    assert.ok(values.title && values.title.length >= 3, `${guide}.md has no title`);
    assert.ok(values.description && values.description.length >= 60, `${guide}.md needs a description of a sentence or so`);
    assert.ok(values.description.length <= 200, `${guide}.md has a description too long for a search snippet`);
    assert.ok(!/[–—]/.test(values.title + values.description), `${guide}.md uses a dash that is not a hyphen`);
  }

  const descriptions = [...byPath.values()].map((values) => values.description).filter(Boolean);
  assert.equal(new Set(descriptions).size, descriptions.length, 'two guides share a description');
});

test('the guides publish as pages only, with a layout, an image and a 404 page', () => {
  assert.equal(config.optional_front_matter.remove_originals, true, 'the raw .md files are published beside the pages');
  const everything = config.defaults.find((entry) => entry.scope.path === '');
  assert.equal(everything.values.layout, 'default');
  assert.ok(fs.existsSync(path.join(DOCS, everything.values.image.replace(/^\//, ''))), 'the default link preview image is missing');
  assert.equal(everything.values.locale, 'en_US');

  const notFound = fs.readFileSync(path.join(DOCS, '404.html'), 'utf8');
  assert.match(notFound, /^---\n[\s\S]*permalink: \/404\.html/);
});

test('the layout gives every guide one h1, a skip link, a main landmark and no outside script', () => {
  const layout = fs.readFileSync(path.join(DOCS, '_layouts', 'default.html'), 'utf8');
  const head = fs.readFileSync(path.join(DOCS, '_includes', 'head-custom.html'), 'utf8');
  const header = fs.readFileSync(path.join(DOCS, '_includes', 'site-header.html'), 'utf8');

  assert.match(layout, /<a class="aw-skip" href="#content">/);
  assert.match(layout, /<main[^>]*id="content"/);
  // The theme drew the site title as an h1 above the page's own; this layout draws none.
  assert.doesNotMatch(layout + header, /<h1\b/);
  assert.match(layout, /theme-color/);

  for (const text of [layout, head, header]) {
    assert.doesNotMatch(text, /<script[^>]+src="https?:/, 'a guide loads a script from another host');
    assert.doesNotMatch(text, /<link[^>]+href="https?:\/\/(?!github\.com)[^"]*\.css/, 'a guide loads a stylesheet from another host');
  }

  // Every link in the header and the drawer goes somewhere that exists.
  assert.match(header, /aria-controls="aw-guides"/);
  assert.match(layout, /id="aw-guides"/);
  assert.ok(fs.existsSync(path.join(DOCS, 'assets', 'js', 'guide.js')));
});

test('every screenshot in a guide has a size, a description and a file', () => {
  for (const guide of guides) {
    const text = fs.readFileSync(path.join(DOCS, `${guide}.md`), 'utf8');
    for (const [tag] of text.matchAll(/<img\b[^>]*>/g)) {
      if (/shields\.io/.test(tag)) continue;
      assert.match(tag, /\swidth="\d+"/, `${guide}.md: ${tag.slice(0, 60)} has no width`);
      assert.match(tag, /\sheight="\d+"/, `${guide}.md: ${tag.slice(0, 60)} has no height, so the page shifts when it loads`);
      assert.match(tag, /\salt="[^"]+"/, `${guide}.md: ${tag.slice(0, 60)} has no description`);
      const source = /src="([^"]+)"/.exec(tag)[1];
      assert.ok(fs.existsSync(path.join(DOCS, source)), `${guide}.md shows ${source}, which is not there`);
    }
  }
});

test('the FAQ is real headings, so every question has an address', () => {
  const faq = fs.readFileSync(path.join(DOCS, 'faq.md'), 'utf8');
  assert.ok((faq.match(/^### .+/gm) || []).length >= 25, 'the FAQ questions are no longer headings');
  assert.doesNotMatch(faq, /^\*\*[^*\n]+\?\*\*$/m, 'a question is a bold line again');

  const faqTool = require(path.join(root, 'tools', 'site', 'faq.js'));
  assert.equal(fs.readFileSync(faqTool.OUT, 'utf8').replace(/\r\n/g, '\n'), faqTool.content(), 'docs/_includes/faq-jsonld.html is stale; run node tools/site/faq.js');
});

test('the search index is current and covers every guide in the list', () => {
  const searchTool = require(path.join(root, 'tools', 'site', 'search-index.js'));
  assert.equal(fs.readFileSync(searchTool.OUT, 'utf8'), searchTool.content(), 'docs/data/search.json is stale; run node tools/site/search-index.js');

  const data = JSON.parse(searchTool.content());
  const indexed = new Set(data.pages.map((page) => page.u));
  for (const item of groups.flatMap((group) => group.items)) {
    assert.ok(indexed.has(`${item.file}.html`), `${item.file} is in the guide list but not in the search index`);
  }
  for (const section of data.sections) {
    assert.ok(data.pages[section.p], 'a section points at no page');
    if (section.a) assert.match(section.a, /^[^\s#]+$/, `"${section.h}" has an anchor a URL cannot carry`);
  }
});

test('search anchors follow the GFM heading rule Jekyll applies', () => {
  const { headingId } = require(path.join(root, 'tools', 'site', 'search-index.js'));
  const seen = new Map();
  assert.equal(headingId('3.11.1 - 2026-10-07', seen), '3111---2026-10-07');
  assert.equal(headingId('Simple and Advanced', seen), 'simple-and-advanced');
  assert.equal(headingId('Simple and Advanced', seen), 'simple-and-advanced-1');
  assert.equal(headingId('Settings, Presets & themes', seen), 'settings-presets--themes');
});

test('the FAQ answers the questions people ask before installing', () => {
  const faq = fs.readFileSync(path.join(DOCS, 'faq.md'), 'utf8');
  for (const topic of [/RetroAchievements/, /new PC/, /Steam Deck/, /portable/i, /SmartScreen/]) {
    assert.match(faq, topic);
  }
});
