'use strict';

/*
  Writes docs/_includes/faq-jsonld.html: the FAQ as schema.org FAQPage data, built from docs/faq.md.

  The questions are the ### headings of the FAQ and the answer is the text under each one, so the
  structured data cannot drift from the page it describes. The layout includes the file on the FAQ
  page only.

    node tools/site/faq.js
    node tools/site/faq.js --check
*/

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..', '..');
const SOURCE = path.join(root, 'docs', 'faq.md');
const OUT = path.join(root, 'docs', '_includes', 'faq-jsonld.html');

// What a reader sees of a Markdown run: link text without the address, no emphasis, no code ticks.
function plain(markdown) {
  let text = markdown.replace(/!\[[^\]]*\]\([^)]*\)/g, '').replace(/\[([^\]]+)\]\([^)]*\)/g, '$1');
  // Repeated until nothing changes, so a removal cannot join two halves into a new tag.
  for (let before = ''; before !== text; ) {
    before = text;
    text = text.replace(/<\/?(?:div|p|br|img|picture|source|sub|sup|b|i|em|strong|a|code|kbd|span)\b[^>]*>/g, '');
  }
  return text
    .replace(/[*_`]+/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function questions() {
  const lines = fs.readFileSync(SOURCE, 'utf8').replace(/\r\n/g, '\n').split('\n');
  const found = [];
  let current = null;
  let fenced = false;

  for (const line of lines) {
    if (line.startsWith('```')) fenced = !fenced;
    const heading = !fenced && /^(#{1,3}) (.+)$/.exec(line);
    if (heading) {
      current = null;
      if (heading[1].length === 3) {
        current = { name: plain(heading[2]), body: [] };
        found.push(current);
      }
      continue;
    }
    // The page closes with a rule and a navigation line that are not part of any answer.
    if (current && /^---\s*$/.test(line)) {
      current = null;
      continue;
    }
    if (current) current.body.push(line);
  }

  return found.map((entry) => ({ name: entry.name, text: plain(entry.body.join('\n')) })).filter((entry) => entry.text);
}

function content() {
  const data = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: questions().map((entry) => ({
      '@type': 'Question',
      name: entry.name,
      acceptedAnswer: { '@type': 'Answer', text: entry.text },
    })),
  };
  // A closing tag inside a string would end the script element early.
  const json = JSON.stringify(data, null, 2).replace(/<\//g, '<\\/');
  return [
    '{% comment %} Generated by tools/site/faq.js from docs/faq.md. {% endcomment %}',
    '<script type="application/ld+json">',
    '{% raw %}',
    json,
    '{% endraw %}',
    '</script>',
    '',
  ].join('\n');
}

function run({ check = false } = {}) {
  const wanted = content();
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== wanted) {
      console.error('docs/_includes/faq-jsonld.html is stale. Run: node tools/site/faq.js');
      process.exitCode = 1;
      return false;
    }
    console.log(`site faq: current (${questions().length} questions)`);
    return true;
  }

  fs.writeFileSync(OUT, wanted, 'utf8');
  console.log(`site faq: generated (${questions().length} questions)`);
  return true;
}

if (require.main === module) run({ check: process.argv.includes('--check') });

module.exports = { OUT, SOURCE, content, questions, run };
