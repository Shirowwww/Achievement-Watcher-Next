'use strict';

/*
  Publish the repository changelog through GitHub Pages without maintaining a second release log.

    node tools/site/changelog.js
    node tools/site/changelog.js --check
*/

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..', '..');
const SOURCE = path.join(root, 'CHANGELOG.md');
const OUT = path.join(root, 'docs', 'changelog.md');

function content() {
  const changelog = fs.readFileSync(SOURCE, 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n').trimEnd();
  return [
    '---',
    'title: Changelog',
    'description: Release history for Achievement Watcher Next.',
    '---',
    '',
    '<!-- Generated by tools/site/changelog.js from /CHANGELOG.md. -->',
    '',
    changelog,
    '',
  ].join('\n');
}

function run({ check = false } = {}) {
  const wanted = content();
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== wanted) {
      console.error('docs/changelog.md is stale. Run: node tools/site/changelog.js');
      process.exitCode = 1;
      return false;
    }
    console.log('site changelog: current');
    return true;
  }

  fs.writeFileSync(OUT, wanted, 'utf8');
  console.log('site changelog: generated');
  return true;
}

if (require.main === module) run({ check: process.argv.includes('--check') });

module.exports = { SOURCE, OUT, content, run };
